    pub fn validate_setting(&self, section: &str, key: &str, value: &str) -> Result<(), String> {
        match (section, key) {
            ("Network", "Timeout") => {
                if let Ok(timeout) = value.parse::<u32>() {
                    if timeout < 5 || timeout > 300 {
                        return Err("Timeout must be between 5 and 300 seconds".to_string());
                    }
                } else {
                    return Err("Timeout must be a number".to_string());
                }
            },
            ("Display", "MinimumFontSize") => {
                if let Ok(size) = value.parse::<u32>() {
                    if size < 1 || size > 72 {
                        return Err("Minimum font size must be between 1 and 72 pixels".to_string());
                    }
                } else {
                    return Err("Minimum font size must be a number".to_string());
                }
            },
            ("Advanced", "CacheSize") => {
                if let Ok(size) = value.parse::<u32>() {
                    if size < 1 || size > 1000 {
                        return Err("Cache size must be between 1 and 1000 MB".to_string());
                    }
                } else {
                    return Err("Cache size must be a number".to_string());
                }
            },
            _ => {} // Other settings don't have validation
        }

        Ok(())
    }

    pub fn set_and_validate(&mut self, section: &str, key: &str, value: &str) -> Result<(), String> {
        self.validate_setting(section, key, value)?;
        self.set_value(section, key, value);
        Ok(())
    }

