    #[test]
    fn test_is_default_value() {
        let temp_file = NamedTempFile::new().unwrap();
        let mut ini = IniPreferences::new(temp_file.path().to_str().unwrap().to_string());

        // Load defaults
        ini.load_defaults();

        // Check that default value returns true
        assert!(ini.is_default_value("General", "HomePage"));

        // Change value and check that it returns false
        ini.set_value("General", "HomePage", "http://changed.com");
        assert!(!ini.is_default_value("General", "HomePage"));
    }

    #[test]
    fn test_get_changed_preferences() {
        let temp_file = NamedTempFile::new().unwrap();
        let mut ini = IniPreferences::new(temp_file.path().to_str().unwrap().to_string());

        // Load defaults
        ini.load_defaults();

        // Change a value
        ini.set_value("General", "HomePage", "http://changed.com");

        // Get changed preferences
        let changed = ini.get_changed_preferences();
        assert_eq!(changed.len(), 1);
        assert_eq!(changed[0].0, "General"); // section
        assert_eq!(changed[0].1, "HomePage"); // key
        assert_eq!(changed[0].2, "http://changed.com"); // value
    }

