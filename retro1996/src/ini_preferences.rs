    pub fn backup_to_file(&self, backup_path: &str) -> Result<(), IniError> {
        let content = self.export_all();
        fs::write(backup_path, content)
            .map_err(|e| IniError::IoError(e))
    }

    pub fn restore_from_backup(&mut self, backup_path: &str) -> Result<(), IniError> {
        if !Path::new(backup_path).exists() {
            return Err(IniError::IoError(std::io::Error::new(
                std::io::ErrorKind::NotFound,
                "Backup file not found"
            )));
        }

        let content = fs::read_to_string(backup_path)
            .map_err(|e| IniError::IoError(e))?;

        self.parse_ini_content(&content)?;
        Ok(())
    }

