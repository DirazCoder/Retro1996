    pub fn migrate_from_old_version(&mut self, old_prefs: &IniPreferences) {
        // Migrate settings from an older version of the preferences
        for (section_name, section_values) in &old_prefs.sections {
            for (key, value) in section_values {
                // Only migrate if the setting doesn't already exist
                if self.get_value(section_name, key).is_none() {
                    self.set_value(section_name, key, value);
                }
            }
        }
    }

